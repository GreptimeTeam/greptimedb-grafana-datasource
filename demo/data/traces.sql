-- Schema compatible with GenAI Observability / legacy OTel dashboards:
-- attributes are flattened into dotted column names (not a single JSON column).

DROP TABLE IF EXISTS public.opentelemetry_traces;

CREATE TABLE IF NOT EXISTS public.opentelemetry_traces (
  "timestamp" TIMESTAMP(3) NOT NULL,
  trace_id STRING NULL,
  span_id STRING NULL,
  parent_span_id STRING NULL,
  service_name STRING NULL,
  span_name STRING NULL,
  duration_nano BIGINT NULL,
  span_status_code STRING NULL,
  span_kind STRING NULL,
  scope_name STRING NULL,
  "span_attributes.gen_ai.system" STRING NULL,
  "span_attributes.gen_ai.operation.name" STRING NULL,
  "span_attributes.gen_ai.request.model" STRING NULL,
  "span_attributes.gen_ai.request.max_tokens" INT NULL,
  "span_attributes.gen_ai.usage.input_tokens" INT NULL,
  "span_attributes.gen_ai.usage.output_tokens" INT NULL,
  "span_attributes.gen_ai.response.finish_reasons" STRING NULL,
  "span_attributes.server.address" STRING NULL,
  "span_attributes.http.route" STRING NULL,
  "resource_attributes.telemetry.sdk.name" STRING NULL,
  "resource_attributes.telemetry.sdk.language" STRING NULL,
  "resource_attributes.telemetry.sdk.version" STRING NULL,
  "resource_attributes.service.name" STRING NULL,
  "resource_attributes.host.name" STRING NULL,
  TIME INDEX ("timestamp"),
  PRIMARY KEY (trace_id, span_id)
);

